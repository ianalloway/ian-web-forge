/**
 * Elliptic curves over a prime field, and the same curve over the reals.
 *
 * y² = x³ + ax + b
 *
 * Over the reals that is a smooth curve and "adding" two points means: draw
 * the line through them, find the third place it crosses, reflect it over the
 * x-axis. Over a prime field the picture becomes a scatter of dots with no
 * geometry left, but the algebra is identical — and that algebra is a group,
 * which is the whole reason the curve is useful for cryptography.
 *
 * Everything here is exact: field arithmetic is bigint, so the same code runs
 * on a 97-element toy curve and on secp256k1.
 */

export interface Curve {
  a: bigint;
  b: bigint;
  p: bigint;
}

/** A point, or null for the point at infinity (the group's identity). */
export type Point = { x: bigint; y: bigint } | null;

/** Least non-negative residue — JS `%` keeps the sign of the dividend. */
export function mod(x: bigint, p: bigint): bigint {
  const r = x % p;
  return r < 0n ? r + p : r;
}

/** Modular inverse by the extended Euclidean algorithm. */
export function inv(x: bigint, p: bigint): bigint {
  const a = mod(x, p);
  if (a === 0n) throw new Error("no inverse for 0");
  let [old_r, r] = [a, p];
  let [old_s, s] = [1n, 0n];
  while (r !== 0n) {
    const q = old_r / r;
    [old_r, r] = [r, old_r - q * r];
    [old_s, s] = [s, old_s - q * s];
  }
  if (old_r !== 1n) throw new Error("not invertible");
  return mod(old_s, p);
}

/**
 * 4a³ + 27b². A curve with a zero discriminant has a cusp or a self
 * intersection, the group law breaks there, so it is not a usable curve.
 */
export function discriminant(c: Curve): bigint {
  return mod(4n * c.a ** 3n + 27n * c.b ** 2n, c.p);
}

export function isSingular(c: Curve): boolean {
  return discriminant(c) === 0n;
}

export function isOnCurve(c: Curve, P: Point): boolean {
  if (P === null) return true; // infinity is on every curve by definition
  const lhs = mod(P.y * P.y, c.p);
  const rhs = mod(P.x ** 3n + c.a * P.x + c.b, c.p);
  return lhs === rhs;
}

export function negate(c: Curve, P: Point): Point {
  return P === null ? null : { x: P.x, y: mod(-P.y, c.p) };
}

export function eq(P: Point, Q: Point): boolean {
  if (P === null || Q === null) return P === Q;
  return P.x === Q.x && P.y === Q.y;
}

/**
 * The group law. The slope is the chord through P and Q, or the tangent when
 * they coincide; reflecting the third intersection gives the sum.
 */
export function add(c: Curve, P: Point, Q: Point): Point {
  if (P === null) return Q;
  if (Q === null) return P;

  if (P.x === Q.x && mod(P.y + Q.y, c.p) === 0n) {
    // Q is -P (including the case y = 0, where P is its own inverse).
    return null;
  }

  let lambda: bigint;
  if (P.x === Q.x && P.y === Q.y) {
    lambda = mod((3n * P.x * P.x + c.a) * inv(2n * P.y, c.p), c.p);
  } else {
    lambda = mod((Q.y - P.y) * inv(Q.x - P.x, c.p), c.p);
  }

  const x = mod(lambda * lambda - P.x - Q.x, c.p);
  const y = mod(lambda * (P.x - x) - P.y, c.p);
  return { x, y };
}

export function double(c: Curve, P: Point): Point {
  return add(c, P, P);
}

/**
 * Scalar multiplication by double-and-add: the operation that is easy forwards
 * and believed hard to reverse. Recovering k from kP is the discrete logarithm
 * problem, and every curve-based scheme rests on it being expensive.
 */
export function mul(c: Curve, k: bigint, P: Point): Point {
  if (k === 0n || P === null) return null;
  if (k < 0n) return negate(c, mul(c, -k, P));
  let result: Point = null;
  let addend: Point = P;
  let n = k;
  while (n > 0n) {
    if (n & 1n) result = add(c, result, addend);
    addend = double(c, addend);
    n >>= 1n;
  }
  return result;
}

/** How many doublings and additions `mul` performs for this scalar. */
export function ladderSteps(k: bigint): { doublings: number; additions: number } {
  let n = k < 0n ? -k : k;
  let doublings = 0;
  let additions = 0;
  while (n > 0n) {
    if (n & 1n) additions++;
    doublings++;
    n >>= 1n;
  }
  return { doublings, additions };
}

/** Every affine point on a small curve, in (x, y) order. Infinity excluded. */
export function allPoints(c: Curve): { x: bigint; y: bigint }[] {
  const out: { x: bigint; y: bigint }[] = [];
  for (let x = 0n; x < c.p; x++) {
    const rhs = mod(x ** 3n + c.a * x + c.b, c.p);
    for (let y = 0n; y < c.p; y++) {
      if (mod(y * y, c.p) === rhs) out.push({ x, y });
    }
  }
  return out;
}

/** #E, the group order — affine points plus the point at infinity. */
export function curveOrder(c: Curve): number {
  return allPoints(c).length + 1;
}

/** The cyclic subgroup generated by G: [G, 2G, 3G, …] up to but not including infinity. */
export function subgroup(c: Curve, G: Point): Point[] {
  const out: Point[] = [];
  let P: Point = G;
  while (P !== null) {
    out.push(P);
    P = add(c, P, G);
    if (out.length > 100000) throw new Error("subgroup too large to enumerate");
  }
  return out;
}

/** The smallest n > 0 with nG = O. */
export function pointOrder(c: Curve, G: Point): number {
  if (G === null) return 1;
  return subgroup(c, G).length + 1;
}

/**
 * Hasse's theorem: the number of points on a curve over F_p is always within
 * 2√p of p + 1. It is why you can pick a random curve and know roughly how
 * big its group will be.
 */
export function hasseInterval(p: bigint): { low: number; high: number } {
  const pn = Number(p);
  const bound = 2 * Math.sqrt(pn);
  return { low: Math.ceil(pn + 1 - bound), high: Math.floor(pn + 1 + bound) };
}

/* ------------------------------ over the reals ----------------------------- */

export interface RealPoint {
  x: number;
  y: number;
}

/**
 * The same group law without the modulus, for drawing the chord-and-tangent
 * construction. Returns null for the point at infinity (a vertical line).
 */
export function addReal(a: number, P: RealPoint, Q: RealPoint): RealPoint | null {
  const sameX = Math.abs(P.x - Q.x) < 1e-12;
  if (sameX && Math.abs(P.y + Q.y) < 1e-12) return null; // vertical chord
  const lambda = sameX ? (3 * P.x * P.x + a) / (2 * P.y) : (Q.y - P.y) / (Q.x - P.x);
  if (!Number.isFinite(lambda)) return null;
  const x = lambda * lambda - P.x - Q.x;
  const y = lambda * (P.x - x) - P.y;
  return { x, y };
}

/** y for a given x on the real curve, or null where the curve has no point. */
export function realY(a: number, b: number, x: number): number | null {
  const rhs = x * x * x + a * x + b;
  return rhs < 0 ? null : Math.sqrt(rhs);
}

/** Is x in the curve's domain over the reals? */
export function realHasPoint(a: number, b: number, x: number): boolean {
  return x * x * x + a * x + b >= 0;
}

